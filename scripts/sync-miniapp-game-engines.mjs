#!/usr/bin/env node
// Sync the nitro-worker's game engines from their canonical TypeScript sources
// in the sibling neo-os-minigames repo — the game-engine arm of the
// estate's single-source pattern (cf. deploy/scripts/sync_morpheus_registry.mjs
// in the miniapps repo).
//
//   node scripts/sync-miniapp-game-engines.mjs           # regenerate in place
//   node scripts/sync-miniapp-game-engines.mjs --check   # drift check (no writes)
//
// For every `generate` engine below, the TS source is bundled with the minigames
// repo's own esbuild (--format=esm --platform=node --bundle, sibling TS imports
// inlined, node:* external) and written to
// workers/nitro-worker/src/game/engines/<name>.js with a GENERATED banner.
// NEVER edit a generated file by hand — edit the TS twin upstream and re-sync.
//
// Engines whose wrapper/tests need enclave-only functions the TS twin does not
// have (the problemSecret deal, answer strings, replay accounting) keep those
// in a HANDWRITTEN engines/<name>.adapter.js — the only module consumers
// import. Engines whose TS twin has drifted behaviorally from the reviewed port
// stay hand-ported (`keep` entries, with the divergence on record); the parity
// goldens (engine-parity.goldens.json) pin their behavior either way.
//
// MINIGAMES_ROOT overrides the sibling repo location (default:
// ../neo-os-minigames). MINIAPPS_ROOT remains a deprecated compatibility alias.

