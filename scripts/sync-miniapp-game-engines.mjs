function sha256Of(buffer) {
  return createHash('sha256').update(buffer).digest('hex');
}

function bannerFor(entry, sourceSha256) {
  return [
    `// GENERATED from neo-os-minigames/${entry.source} by scripts/sync-miniapp-game-engines.mjs — DO NOT EDIT.`,
    `// Source sha256: ${sourceSha256}. After a reviewed upstream change, re-run this sync and the parity goldens.`,
    '',
  ].join('\n');
}

// Bundle one TS source with the miniapps repo's own esbuild. Runs with cwd =
// miniappsRoot and a RELATIVE entry so the emitted section comments carry
// repo-relative paths (deterministic across machines).
function bundleSource(minigamesRoot, entry) {
  const esbuild = path.join(minigamesRoot, 'node_modules', '.bin', 'esbuild');
  if (!fs.existsSync(esbuild)) {
    throw new Error(`missing esbuild: ${esbuild} (run npm install in the minigames repo)`);
  }
  const sourcePath = path.join(minigamesRoot, entry.source);
  if (!fs.existsSync(sourcePath)) {
    throw new Error(`missing canonical source for engine '${entry.name}': ${sourcePath}`);
  }
  const sourceSha256 = sha256Of(fs.readFileSync(sourcePath));

  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'engine-sync-'));
  try {
    const outFile = path.join(tmpDir, `${entry.name}.js`);
    execFileSync(
      esbuild,
      [entry.source, '--format=esm', '--platform=node', '--bundle', `--outfile=${outFile}`],
      { cwd: minigamesRoot, stdio: ['ignore', 'pipe', 'pipe'] }
    );
    const bundle = fs.readFileSync(outFile, 'utf8');
    return `${bannerFor(entry, sourceSha256)}${bundle}`;
  } finally {
    fs.rmSync(tmpDir, { recursive: true, force: true });
  }
}

// Generate every `generate` engine into `${outRoot}/<name>.js`.
// Returns a manifest of { name, sha256, sourceSha256 } per written file.
export function buildEngines({ minigamesRoot, miniappsRoot, outRoot = ENGINES_OUT_DIR } = {}) {
  const canonicalRoot = minigamesRoot || miniappsRoot || defaultMinigamesRoot;
  if (!fs.existsSync(canonicalRoot)) {
    throw new Error(`minigames repo not found at ${canonicalRoot} (set MINIGAMES_ROOT)`);
  }
  // Every mapped source must exist — a renamed/deleted upstream file is a
  // mapping bug and fails loudly here, generate or keep.
  const missing = ENGINE_SOURCES.filter(
    (entry) => !fs.existsSync(path.join(canonicalRoot, entry.source))
  ).map((entry) => `${entry.name}: ${entry.source}`);
  if (missing.length > 0) {
    throw new Error(`canonical sources missing under ${canonicalRoot}:\n${missing.join('\n')}`);
  }
  fs.mkdirSync(outRoot, { recursive: true });

  const manifest = [];
  const failures = [];
  for (const entry of ENGINE_SOURCES) {
    if (entry.action !== 'generate') continue;
    try {
      const content = bundleSource(canonicalRoot, entry);
      const outPath = path.join(outRoot, `${entry.name}.js`);
      fs.writeFileSync(outPath, content, 'utf8');
      manifest.push({ name: entry.name, source: entry.source, sha256: sha256Of(content) });
    } catch (error) {
      failures.push(`${entry.name}: ${error instanceof Error ? error.message : String(error)}`);
    }
  }
  if (failures.length > 0) {
    throw new Error(`sync failed:\n${failures.join('\n')}`);
  }
  return manifest;
}

// Re-generate into a temp dir and byte-compare against the checked-in files.
export function driftReport({ minigamesRoot, miniappsRoot } = {}) {
  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'engine-drift-'));
  try {
    const manifest = buildEngines({ minigamesRoot, miniappsRoot, outRoot: tmpDir });
    const drifted = [];
    for (const item of manifest) {
      const checkedIn = path.join(ENGINES_OUT_DIR, `${item.name}.js`);
      if (!fs.existsSync(checkedIn)) {
        drifted.push(`${item.name}: checked-in file missing`);
        continue;
      }
      if (sha256Of(fs.readFileSync(checkedIn)) !== item.sha256) {
        drifted.push(`${item.name}: stale (re-run scripts/sync-miniapp-game-engines.mjs)`);
      }
    }
    return { drifted, manifest };
  } finally {
    fs.rmSync(tmpDir, { recursive: true, force: true });
  }
}

async function main() {
  const configuredRoot = process.env.MINIGAMES_ROOT || process.env.MINIAPPS_ROOT;
  const minigamesRoot = configuredRoot ? path.resolve(configuredRoot) : defaultMinigamesRoot;

  if (process.argv.includes('--check')) {
    const { drifted, manifest } = driftReport({ minigamesRoot });
    for (const item of manifest) {
      console.log(`✔ regenerated ${item.name}.js (sha256 ${item.sha256.slice(0, 12)}…)`);
    }
    if (drifted.length > 0) {
      console.error(`drift detected:\n${drifted.join('\n')}`);
      process.exitCode = 1;
    } else {
      console.log('Checked-in generated engines are up to date.');
    }
    return;
  }

  const manifest = buildEngines({ minigamesRoot });
  for (const item of manifest) {
    console.log(`wrote workers/nitro-worker/src/game/engines/${item.name}.js from ${item.source}`);
  }
  const kept = ENGINE_SOURCES.filter((e) => e.action === 'keep');
  console.log(
    `kept ${kept.length} engines handwritten (${kept.map((e) => e.name).join(', ')}) — see ENGINE_SOURCES reasons.`
  );
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  });
}
