// npm dependency policy for this workspace, run by ci.yml lint-and-format.
//
// Every workspace (apps/*, workers/*, packages/*) installs from the root
// package-lock.json: `npm ci` at the root, `cd apps/web && npm ci`, both worker
// images (they copy only the manifests and the root lock before `npm ci`) and
// the Vercel build of apps/web, which .vercelignore documents as building from
// the monorepo root. The root `npm audit` and lockfile drift steps in
// lint-and-format therefore cover apps/web; this file pins the patched versions
// the apps/web closure must keep and the invariants that keep one lockfile the
// only one that matters.
//
// History: e4b02a7 added the apps/web audit and lockfile gates to the NeoSwap
// CI job, run with `npm --prefix apps/web` against a separate
// apps/web/package-lock.json. 7f430ab deleted that job with services/neoswap,
// and this file died at load on the missing services/neoswap/package.json. That
// separate lockfile was only ever read by those `--prefix` steps; it disagreed
// with the root lock on 231 of its 781 packages, so it is gone.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import test from 'node:test';

import { parseWorkflowJobs } from './lib-workflow-graph.mjs';

const root = path.resolve(import.meta.dirname, '..');
const require = createRequire(import.meta.url);
const semver = require(path.join(root, 'node_modules', 'semver'));

function readJson(relative) {
  return JSON.parse(fs.readFileSync(path.join(root, relative), 'utf8'));
}

const rootManifest = readJson('package.json');
const rootLock = readJson('package-lock.json');
const webManifest = readJson('apps/web/package.json');
const workflow = fs.readFileSync(path.join(root, '.github', 'workflows', 'ci.yml'), 'utf8');

function workspaceDirs() {
  const dirs = [];
  for (const pattern of rootManifest.workspaces) {
    assert.match(pattern, /^[\w.-]+\/\*$/, `unsupported workspace pattern ${pattern}`);
    const parent = pattern.slice(0, -2);
    for (const entry of fs.readdirSync(path.join(root, parent), { withFileTypes: true })) {
      if (entry.isDirectory() && fs.existsSync(path.join(root, parent, entry.name, 'package.json')))
        dirs.push(`${parent}/${entry.name}`);
    }
  }
  return dirs.sort();
}

function lockVersions(name) {
  return Object.entries(rootLock.packages ?? {})
    .filter(([key]) => key === `node_modules/${name}` || key.endsWith(`/node_modules/${name}`))
    .map(([key, value]) => ({ key, version: value.version }));
}

function packageNameFromLockKey(key) {
  const packagePath = key.slice(key.lastIndexOf('node_modules/') + 'node_modules/'.length);
  const parts = packagePath.split('/');
  return parts[0].startsWith('@') ? parts.slice(0, 2).join('/') : parts[0];
}

function jobBody(name) {
  const job = parseWorkflowJobs(workflow).find((candidate) => candidate.name === name);
  assert.ok(job, `ci.yml no longer defines the ${name} job`);
  return job.body;
}

test('the root lockfile is generated by the pinned npm', () => {
  assert.equal(rootManifest.packageManager, 'npm@10.9.2');
  assert.equal(rootLock.lockfileVersion, 3);
});

test('every workspace installs from the root lock and nothing else', () => {
  const workspaces = workspaceDirs();
  assert.ok(workspaces.includes('apps/web'), 'apps/web must stay a workspace of the root lock');
  for (const dir of workspaces) {
    // A nested lock is never read by a root install, so it can only drift.
    for (const lockName of ['package-lock.json', 'npm-shrinkwrap.json']) {
      assert.equal(
        fs.existsSync(path.join(root, dir, lockName)),
        false,
        `${dir}/${lockName} would shadow nothing and drift from the root lock`
      );
    }
    const manifest = readJson(`${dir}/package.json`);
    const entry = rootLock.packages?.[dir];
    assert.ok(entry, `the root lock has no entry for workspace ${dir}`);
    for (const group of [
      'dependencies',
      'devDependencies',
      'optionalDependencies',
      'peerDependencies',
    ]) {
      assert.deepEqual(
        entry[group] ?? {},
        manifest[group] ?? {},
        `the root lock's ${dir} ${group} do not mirror ${dir}/package.json`
      );
    }
    // npm reads `overrides` from the root manifest only; one declared in a
    // workspace is ignored and reads as a pin that is not applied.
    assert.equal(manifest.overrides, undefined, `${dir}/package.json declares ignored overrides`);
  }
});

test('the declared Node range is one every installed package supports', () => {
  // `>=22 <25` admitted Node versions below the undici@8 floor (>=22.19.0) that
  // workers/nitro-worker runs on, and odd-numbered Node 23, which vite, vitest
  // and rolldown do not support.
  const declared = rootManifest.engines?.node;
  assert.ok(semver.validRange(declared), `engines.node ${declared} is not a valid range`);
  assert.equal(rootLock.packages?.['']?.engines?.node, declared, 'the root lock records engines');
  const unsupported = [];
  for (const [key, value] of Object.entries(rootLock.packages ?? {})) {
    const floor = value.engines?.node;
    if (!key || typeof floor !== 'string') continue;
    // Platform binaries for systems this repository never builds on (for
    // example the optional win32/ia32 sharp build) are never installed.
    if (Array.isArray(value.os) && !value.os.some((os) => os === 'linux' || os === 'darwin'))
      continue;
    if (!semver.subset(declared, floor))
      unsupported.push(`${key.replace(/^.*node_modules\//, '')}@${value.version} needs ${floor}`);
  }
  assert.deepEqual(unsupported, [], `engines.node ${declared} admits unsupported Node versions`);
});

test('the apps/web closure resolves to patched versions', () => {
  assert.equal(webManifest.dependencies?.next, '^15.5.26');
  assert.equal(webManifest.devDependencies?.['eslint-config-next'], '^15.5.26');
  assert.equal(webManifest.devDependencies?.vitest, '^4.1.11');
  assert.equal(rootManifest.overrides?.['fast-uri'], '3.1.6');
  assert.equal(rootManifest.overrides?.sharp, '0.35.4');

  const floors = {
    next: '15.5.24',
    'eslint-config-next': '15.5.24',
    vitest: '4.1.11',
    '@vitest/mocker': '4.1.11',
    'fast-uri': '3.1.6',
    browserslist: '4.28.7',
    'baseline-browser-mapping': '2.11.0',
    sharp: '0.35.4',
  };
  for (const [name, floor] of Object.entries(floors)) {
    for (const { key, version } of lockVersions(name))
      assert.ok(
        semver.gte(version, floor),
        `${key} has vulnerable ${name} ${version} (< ${floor})`
      );
  }
  for (const { key, version } of lockVersions('js-yaml')) {
    const floor = version.startsWith('3.') ? '3.15.2' : version.startsWith('4.') ? '4.3.2' : null;
    assert.ok(!floor || semver.gte(version, floor), `${key} has vulnerable js-yaml ${version}`);
  }
  // The floors above must bind to something: apps/web really resolves these.
  for (const name of ['next', 'eslint-config-next', 'vitest', '@vitest/mocker', 'sharp']) {
    assert.ok(lockVersions(name).length > 0, `the root lock no longer resolves ${name}`);
  }
});

test('high severity transitive advisories stay above their remediation floors', () => {
  const floors = {
    'brace-expansion': {
      '1.': '1.1.21',
      '5.': '5.0.12',
    },
    undici: {
      '8.': '8.10.2',
    },
  };

  for (const [name, majorFloors] of Object.entries(floors)) {
    const versions = lockVersions(name);
    assert.ok(versions.length > 0, `the root lock no longer resolves ${name}`);
    for (const { key, version } of versions) {
      const floor = Object.entries(majorFloors).find(([prefix]) => version.startsWith(prefix))?.[1];
      assert.ok(floor, `${key} resolves unreviewed ${name}@${version}`);
      assert.ok(
        semver.gte(version, floor),
        `${key} resolves vulnerable ${name}@${version}; expected at least ${floor}`
      );
    }
  }
});

test('every locked registry package is pinned to its tarball with a SHA-512 digest', () => {
  let checked = 0;
  for (const [key, value] of Object.entries(rootLock.packages ?? {})) {
    if (!key.includes('node_modules/') || value.link || value.inBundle) continue;
    checked += 1;
    assert.match(value.resolved ?? '', /^https:\/\/registry\.npmjs\.org\//, `${key} resolved`);
    const integrity = (value.integrity ?? '').match(/^sha512-([A-Za-z0-9+/]+={0,2})$/);
    assert.ok(integrity, `${key} is missing a SHA-512 integrity pin`);
    assert.equal(Buffer.from(integrity[1], 'base64').byteLength, 64, `${key} integrity length`);
    const tarballName = packageNameFromLockKey(key).split('/').at(-1);
    assert.ok(
      new URL(value.resolved).pathname.endsWith(`/-/${tarballName}-${value.version}.tgz`),
      `${key} resolved tarball is not bound to ${tarballName}@${value.version}`
    );
  }
  assert.ok(checked > 500, `only ${checked} locked packages checked; the lock was not read`);
});

test('lint-and-format audits the root lock, guards its drift and runs this policy', () => {
  const lint = jobBody('lint-and-format');
  assert.match(lint, /^\s*- run: npm ci\s*$/m);
  assert.match(lint, /^\s*- run: npm audit --audit-level=moderate\s*$/m);
  assert.match(lint, /npm install --package-lock-only\n\s*git diff --exit-code package-lock\.json/);
  assert.match(lint, /^\s*- run: node --test scripts\/dependency-security\.test\.mjs\s*$/m);
});

test('every paths-filter output of the changes job gates some job', () => {
  const outputs = [
    ...jobBody('changes').matchAll(/^ {6}([\w-]+): \$\{\{ steps\.filter\.outputs/gm),
  ];
  assert.ok(outputs.length > 0, 'the changes job declares no filter outputs');
  const consumers = parseWorkflowJobs(workflow).filter((job) => job.name !== 'changes');
  for (const [, output] of outputs) {
    assert.ok(
      consumers.some((job) => job.condition.includes(`needs.changes.outputs.${output}`)),
      `changes output '${output}' is read by no job; a dead filter reads as coverage`
    );
  }
});
